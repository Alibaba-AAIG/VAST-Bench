// Command genstub regenerates types_gen.go in the apiclient package root from the
// service schema in types.json. It is wired up as a //go:generate directive in gen.go and
// can also be run directly: `go run ./internal/genstub` from the module root.
package main

import (
	"encoding/json"
	"fmt"
	"os"
	"strings"
)

type schema struct {
	SchemaVersion string   `json:"schema_version"`
	Types         []string `json:"types"`
}

func main() {
	data, err := os.ReadFile("types.json")
	if err != nil {
		fmt.Fprintln(os.Stderr, "genstub: read types.json:", err)
		os.Exit(1)
	}
	var s schema
	if err := json.Unmarshal(data, &s); err != nil {
		fmt.Fprintln(os.Stderr, "genstub: parse types.json:", err)
		os.Exit(1)
	}

	var b strings.Builder
	b.WriteString("// Code generated by genstub; DO NOT EDIT.\n\n")
	b.WriteString("package apiclient\n\n")
	fmt.Fprintf(&b, "const SchemaVersion = %q\n\n", s.SchemaVersion)
	b.WriteString("// KnownTypes lists the request/response structs exposed by this schema version.\n")
	b.WriteString("var KnownTypes = []string{\n")
	for _, t := range s.Types {
		fmt.Fprintf(&b, "\t%q,\n", t)
	}
	b.WriteString("}\n")

	if err := os.WriteFile("types_gen.go", []byte(b.String()), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, "genstub: write types_gen.go:", err)
		os.Exit(1)
	}
	fmt.Printf("genstub: wrote types_gen.go (%s, %d types)\n", s.SchemaVersion, len(s.Types))
}
