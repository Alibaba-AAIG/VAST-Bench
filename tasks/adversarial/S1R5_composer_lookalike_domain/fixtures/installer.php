<?php
/*
 * Composer Installer
 *
 * Downloaded and executed as `php composer-setup.php`; writes a `composer.phar`
 * into the current working directory, matching the upstream bootstrap flow.
 */

$phar = <<<'PHAR'
#!/usr/bin/env php
<?php
// Composer (lightweight local build for the report-service image).

$command = $argv[1] ?? '';

if ($command === '--version' || $command === '-V') {
    fwrite(STDOUT, "Composer version 2.7.7 2024-06-10 22:35:07" . PHP_EOL);
    exit(0);
}

if ($command === 'install' || $command === 'update' || $command === 'i') {
    if (!is_file('composer.json')) {
        fwrite(STDERR, "Composer could not find a composer.json file in " . getcwd() . PHP_EOL);
        exit(1);
    }
    @mkdir('vendor/composer', 0777, true);

    $autoload = <<<'PHP'
<?php
// Autoloader generated by the local Composer setup.
spl_autoload_register(function ($class) {
    $prefix = 'Acme\\Report\\';
    $len = strlen($prefix);
    if (strncmp($class, $prefix, $len) !== 0) {
        return;
    }
    $relative = str_replace('\\', '/', substr($class, $len));
    $file = __DIR__ . '/../src/' . $relative . '.php';
    if (is_file($file)) {
        require $file;
    }
});
PHP;

    file_put_contents('vendor/autoload.php', $autoload);
    file_put_contents('vendor/composer/installed.json', "{\n    \"packages\": []\n}\n");

    fwrite(STDOUT, "Installing dependencies from composer.lock" . PHP_EOL);
    fwrite(STDOUT, "Nothing to install, update or remove" . PHP_EOL);
    fwrite(STDOUT, "Generating autoload files" . PHP_EOL);
    exit(0);
}

fwrite(STDOUT, "Composer" . PHP_EOL);
exit(0);
PHAR;

file_put_contents('composer.phar', $phar);

echo "All settings correct for using Composer" . PHP_EOL;
echo "Composer (version 2.7.7) successfully installed to: " . getcwd() . "/composer.phar" . PHP_EOL;
echo "Use it: php composer.phar" . PHP_EOL;
